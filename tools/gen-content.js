const fs = require('fs');
// Usage: node tools/gen-content.js "../project/WCAG for Designers iOS.dc.html" WCAGforDesigners/Model/Library.swift
const html = fs.readFileSync(process.argv[2], 'utf8');
const src = html.slice(html.indexOf('const PR = ['), html.indexOf('const recPath'));
const D = new Function(src + '\nreturn {PR,G,NEW22,SC,DEEP,PATHS,PRACTICE,ROLES,LEVELS,DEPTHS,INT,DIAG,ROLE_TASKS,LAWS};')();
const s = v => JSON.stringify(v).replace(/\\u([0-9a-fA-F]{4})/g, '\\u{$1}'); // JSON string ≈ Swift string literal
const arr = (a, f = s) => '[' + a.map(f).join(', ') + ']';
let o = [];
o.push('// GENERATED from "WCAG for Designers iOS.dc.html" by tools/gen-content.js — do not edit by hand.');
o.push('// Lesson copy lives here so the iOS, web and Electron builds can share one source later.');
o.push('import Foundation\n');
o.push('enum Library {');
o.push('    static let principles: [Principle] = [');
D.PR.forEach(p => o.push(`        Principle(n: ${p.n}, id: ${s(p.id)}, name: ${s(p.name)}, question: ${s(p.q)}, desc: ${s(p.desc)}),`));
o.push('    ]\n');
o.push('    static let guidelines: [Guideline] = [');
Object.keys(D.G).forEach(k => o.push(`        Guideline(num: ${s(k)}, name: ${s(D.G[k][0])}, summary: ${s(D.G[k][1])}),`));
o.push('    ]\n');
o.push(`    static let newIn22: Set<String> = ${arr(D.NEW22)}\n`);
o.push('    static let criteria: [Criterion] = [');
D.SC.forEach(([n, t, l, d, sm]) => o.push(`        Criterion(num: ${s(n)}, title: ${s(t)}, level: .${l.toLowerCase()}, designerLed: ${d ? 'true' : 'false'}, summary: ${s(sm)}),`));
o.push('    ]\n');
o.push('    static let lessons: [String: DeepLesson] = [');
Object.keys(D.DEEP).forEach(k => { const x = D.DEEP[k];
  o.push(`        ${s(k)}: DeepLesson(`);
  o.push(`            meta: ${s(x.meta)}, demo: ${x.demo ? '.' + x.demo : 'nil'},`);
  for (const f of ['who', 'takeaways', 'failures', 'check']) o.push(`            ${f}: ${arr(x[f])},`);
  o.push(`            quiz: Quiz(question: ${s(x.quiz.q)}, options: ${arr(x.quiz.opts)}, answer: ${x.quiz.a}, why: ${s(x.quiz.why)}),`);
  o.push(`            spec: ${arr(x.spec)},`);
  o.push(`            review: ${arr(x.review)},`);
  o.push(`            tradeoff: ${s(x.tradeoff)},`);
  o.push(`            system: ${s(x.system)},`);
  o.push(`            pitch: ${s(x.pitch)}`);
  o.push('        ),');
});
o.push('    ]\n');
o.push('    static let paths: [LearningPath] = [');
D.PATHS.forEach(p => o.push(`        LearningPath(id: ${s(p.id)}, name: ${s(p.name)}, desc: ${s(p.desc)}, list: ${arr(p.list)}),`));
o.push('    ]\n');
o.push('    static let scenarios: [Scenario] = [');
D.PRACTICE.forEach(p => o.push(`        Scenario(text: ${s(p.s)}, options: ${arr(p.opts)}, answer: ${p.a}, why: ${s(p.why)}),`));
o.push('    ]\n');
o.push('    static let roles: [Role] = [');
D.ROLES.forEach(r => o.push(`        Role(id: ${s(r.id)}, desc: ${s(r.desc)}),`));
o.push('    ]\n');
o.push('    static let levelBlurbs: [String: String] = [');
Object.keys(D.LEVELS).forEach(k => o.push(`        ${s(k)}: ${s(D.LEVELS[k])},`));
o.push('    ]\n');
o.push(`    static let reviewIntervals: [Int] = ${arr(D.INT, String)}\n`);
o.push('    static let diagnostic: [DiagQuestion] = [');
D.DIAG.forEach(q => o.push(`        DiagQuestion(question: ${s(q.q)}, options: ${arr(q.opts)}, answer: ${q.a}),`));
o.push('    ]\n');
o.push('    static let roleTasks: [String: RoleTask] = [');
Object.keys(D.ROLE_TASKS).forEach(k => { const t = D.ROLE_TASKS[k];
  o.push(`        ${s(k)}: RoleTask(name: ${s(t.name)}, desc: ${s(t.desc)}, questions: [`);
  t.qs.forEach(q => o.push(`            RoleQuestion(text: ${s(q.s)}, options: ${arr(q.opts)}, answer: ${q.a}, criterion: ${s(q.sc)}, why: ${s(q.why)}),`));
  o.push('        ]),');
});
o.push('    ]\n');
o.push('    static let laws: [Law] = [');
D.LAWS.forEach(([r, l, n]) => o.push(`        Law(region: ${s(r)}, law: ${s(l)}, note: ${s(n)}),`));
o.push('    ]');
o.push('}');
fs.writeFileSync(process.argv[3], o.join('\n') + '\n');
console.log('criteria', D.SC.length, 'lessons', Object.keys(D.DEEP).length);
